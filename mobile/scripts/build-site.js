/* Packs ../v2 (HTML, CSS, JS, fonts, images) into one self-contained page and writes it to
   site.js, which App.js hands to the WebView. Runs automatically before `npm start`.
   Optional: `node scripts/build-site.js out.html` also writes the page as a plain file. */
const fs = require('fs');
const path = require('path');

const src = path.resolve(__dirname, '..', '..', 'v2');
const read = (file) => fs.readFileSync(path.join(src, file), 'utf8');
const dataUri = (file, mime) => `data:${mime};base64,${fs.readFileSync(path.join(src, file)).toString('base64')}`;

let css = read('styles.css').replace(/url\("(fonts\/[^"]+\.woff2)"\)/g, (_, file) => `url("${dataUri(file, 'font/woff2')}")`);
const js = read('app.js');
if (/<\/script/i.test(js)) throw new Error('app.js contains a closing script tag and cannot be inlined as-is');

let html = read('index.html');
const swap = (pattern, replacement, what) => {
  if (!pattern.test(html)) throw new Error(`build-site: could not find ${what} in v2/index.html`);
  html = html.replace(pattern, replacement);
};
html = html.replace(/^\s*<link rel="preload"[^>]*>\r?\n/gm, '');
swap(/<link rel="stylesheet" href="styles\.css[^"]*">/, () => `<style>${css}</style>`, 'the stylesheet link');
swap(/<script src="app\.js[^"]*"><\/script>/, () => `<script>${js}</script>`, 'the script tag');
html = html.replace(/url\('(img\/[^']+\.jpg)'\)/g, (_, file) => `url('${dataUri(file, 'image/jpeg')}')`);

const left = html.match(/(?:href|src)="(?!#|data:|tel:)[^"]+"|url\((?!['"]?(?:data:|#))[^)]+\)/g);
if (left) throw new Error(`build-site: these still point at separate files: ${left.map((s) => s.slice(0, 80)).join(', ')}`);

fs.writeFileSync(path.resolve(__dirname, '..', 'site.js'), `// Generated by scripts/build-site.js from ../v2. Do not edit.\nexport default ${JSON.stringify(html)};\n`);
if (process.argv[2]) fs.writeFileSync(path.resolve(process.argv[2]), html);
console.log(`site.js written (${Math.round(html.length / 1024)} KB)`);
